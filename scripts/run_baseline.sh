#!/usr/bin/env bash
# 基线入口：固定 runtime / sandbox / registry / config，保证可复现。
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BENCH_ROOT="${BENCH_ROOT:-$REPO_ROOT/benchmarks/PAST-Bench}"
PAST_BENCH="${BENCH_ROOT}/.venv/bin/past-bench"

FAMILY=""
RUN_ID=""
AGENT="hermes"
PROFILE="${PROFILE:-qwen}"
TRACE_DIR=""
JUDGE_MODEL=""

usage() {
  cat <<'EOF'
用法: bash scripts/run_baseline.sh --family <ability/family_id> --run-id <RUN_ID> [选项]

必填:
  --family     例如 memory_ability/SM01_preference_adoption
  --run-id     运行目录名，例如 20261119_sm01_hermes

可选:
  --agent      默认 hermes
  --profile    默认 qwen（或 $PROFILE）
  --trace-dir  默认 $REPO_ROOT/experiments/<run-id>
  --judge-model 覆盖 config.yaml 中的 judge
  -h, --help   显示帮助

前置:
  export QWEN_API_KEY=...
  $BENCH_ROOT/.venv 已安装依赖
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --family) FAMILY="$2"; shift 2 ;;
    --run-id) RUN_ID="$2"; shift 2 ;;
    --agent) AGENT="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    --trace-dir) TRACE_DIR="$2"; shift 2 ;;
    --judge-model) JUDGE_MODEL="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "未知参数: $1" >&2; usage; exit 2 ;;
  esac
done

if [[ -z "$FAMILY" || -z "$RUN_ID" ]]; then
  usage
  exit 2
fi
if [[ -z "${QWEN_API_KEY:-}" ]]; then
  echo "缺少 QWEN_API_KEY" >&2
  exit 2
fi
if [[ ! -x "$PAST_BENCH" ]]; then
  echo "找不到 $PAST_BENCH，请先安装 benchmarks/PAST-Bench 依赖" >&2
  exit 2
fi

TRACE_DIR="${TRACE_DIR:-$REPO_ROOT/experiments/$RUN_ID}"
mkdir -p "$TRACE_DIR"

CMD=(
  "$PAST_BENCH" evolve
  --family "$FAMILY"
  --agent "$AGENT"
  --agent-profile "$PROFILE"
  --runtime local
  --sandbox
  --sandbox-tools
  --compare-no-persistence
  --registry "$REPO_ROOT/configs/agents.yaml"
  --config "$REPO_ROOT/config.yaml"
  --trace-dir "$TRACE_DIR"
)
if [[ -n "$JUDGE_MODEL" ]]; then
  CMD+=(--judge-model "$JUDGE_MODEL")
fi

{
  echo "# generated by scripts/run_baseline.sh"
  echo "QWEN_MODEL_PROFILE=$PROFILE"
  echo "FAMILY=$FAMILY"
  echo "AGENT=$AGENT"
  echo "TRACE_DIR=$TRACE_DIR"
  printf '%q ' "${CMD[@]}"
  echo
} > "$TRACE_DIR/cmd.txt"

echo "[run_baseline] family=$FAMILY agent=$AGENT profile=$PROFILE"
echo "[run_baseline] trace_dir=$TRACE_DIR"
cd "$BENCH_ROOT"
"${CMD[@]}"
